export function createNarrative({ random = Math.random, now = Date.now, maxUsers = 1500 } = {}) {
  const memory = new Map()
  return function narrativeLine(kind, jid = '') {
    const lines = STORY_LINES[kind]
    if (!lines) return ''
    const key = String(jid) + ':' + kind
    let entry = memory.get(key)
    const time = now()
    const cooldown = kind === 'work' ? 30 * 60000 : kind === 'dungeon' ? 20 * 60000 : 0
    if (entry && cooldown && time - entry.at < cooldown) return ''
    const chance = kind === 'work' ? 0.35 : kind === 'dungeon' ? 0.20 : 1
    if (chance < 1 && random() >= chance) return ''
    // Reabrir misiones conserva el mismo apunte durante el día, sin farmear escenas.
    const day = Math.floor((time - 6 * 3600000) / 86400000)
    if (kind === 'missions' && entry?.day === day) return '\n\n📖 *Apunte del viajero*\n' + lines[entry.last]
    if (!entry) entry = { bag: [], last: -1, at: 0 }
    if (!entry.bag.length) {
      entry.bag = lines.map((_, i) => i)
      for (let i = entry.bag.length - 1; i > 0; i--) {
        const j = Math.floor(random() * (i + 1))
        ;[entry.bag[i], entry.bag[j]] = [entry.bag[j], entry.bag[i]]
      }
      if (entry.bag.at(-1) === entry.last) [entry.bag[0], entry.bag[entry.bag.length - 1]] = [entry.bag.at(-1), entry.bag[0]]
    }
    entry.last = entry.bag.pop()
    entry.at = time
    entry.day = day
    if (memory.has(key)) memory.delete(key)
    memory.set(key, entry)
    while (memory.size > maxUsers) memory.delete(memory.keys().next().value)
    return '\n\n📖 *Apunte del viajero*\n' + lines[entry.last]
  }
}

export const narrativeLine = createNarrative()
